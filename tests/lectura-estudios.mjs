import assert from 'node:assert/strict';
import { conciliarEstudios, descripcionEstudios } from '../core/lecturaEstudios.js';
const manifest = [{ ruta: 'qa/lab.pdf', nombre: 'Laboratorio original.pdf', bytes: 1234 }];
assert.equal(conciliarEstudios('qa', manifest, [])[0].disponible, false);
const unido = conciliarEstudios('qa', manifest, [{ ruta: 'qa/lab.pdf', nombre: 'lab.pdf', size: 1234 }]);
assert.equal(unido.length, 1);
assert.equal(unido[0].nombre, 'Laboratorio original.pdf');
assert.equal(unido[0].disponible, true);
assert.equal(conciliarEstudios('qa', [...manifest, ...manifest], []).length, 1);
assert.equal(conciliarEstudios('qa', [{ ruta: 'otra/paciente.pdf' }], [])[0].asociacionValida, false);
assert.equal(conciliarEstudios(null, manifest, [])[0].asociacionValida, false);
assert.equal(conciliarEstudios('qa', manifest, [{ ruta: 'qa/lab.pdf', size: 0 }])[0].integridad, 'vacio');
assert.equal(conciliarEstudios('qa', manifest, [{ ruta: 'qa/lab.pdf', size: 99 }])[0].integridad, 'diferente');
assert.match(descripcionEstudios({}), /Sin registro/);
assert.match(descripcionEstudios({ estudiosFolder: 'qa' }), /por comprobar/);
assert.match(descripcionEstudios({ adjuntos: manifest }), /1 archivo/);
assert.match(descripcionEstudios({ estudiosDeclaracion: 'adjunto_estudios' }), /no hay carpeta/);
assert.match(descripcionEstudios({ estudiosDeclaracion: 'no_los_tengo_ahora' }), /indicó/);
console.log('Lectura de estudios: 14 comprobaciones correctas, datos sintéticos.');
