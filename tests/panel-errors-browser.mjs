import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { respuestasPrueba } from './panel-fixtures.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.env.PANEL_QA_URL || 'http://127.0.0.1:5197';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname));
const output = process.env.PANEL_QA_OUTPUT || path.resolve('../output/jornada-aplicada-20260910');
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.PANEL_QA_BROWSER || 'chrome' });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await context.route('**/*', r => ['127.0.0.1', 'localhost'].includes(new URL(r.request().url()).hostname) ? r.continue() : r.abort());
const mock = await fs.readFile(new URL('./panel-mock-services.mjs', import.meta.url), 'utf8');
await context.route('**/core/respuestas.js*', r => r.fulfill({ contentType: 'text/javascript', body: mock }));
await context.route('**/core/trabajo.js*', r => {
  if (r.request().url().includes('qa_passthrough')) return r.continue();
  return r.fulfill({ contentType: 'text/javascript', body: `export * from '/core/trabajo.js?qa_passthrough=1';
  import {listarTrabajos as original} from '/core/trabajo.js?qa_passthrough=1';
  export async function listarTrabajos(){const t=await original(); if(window.__panelQa.conflictoIndice){for(const i of Object.values(t.porClave)) i.estado='conflicto';} return t;}` });
});
await context.route('**/core/agenda.js*', r => {
  if (r.request().url().includes('qa_passthrough')) return r.continue();
  return r.fulfill({ contentType: 'text/javascript', body: `export {cruzarAgenda,hoyLocal} from '/core/agenda.js?qa_passthrough=1';
  export async function agendaDeHoy(){if(window.__panelQa.errorAgenda) throw Error('QA agenda failure'); return [];}` });
});
await context.addInitScript(records => { window.__panelQa = { respuestas: records, errorAgenda: true, errorEstudios: true, archivos: [] }; }, respuestasPrueba.slice(0, 2));
const page = await context.newPage();
const pruebas = [], errores = [];
const check = (s, c) => { assert.ok(c, s); pruebas.push(s); };
page.on('pageerror', e => errores.push(e.message));
page.on('dialog', d => d.accept());
const nav = name => page.getByRole('navigation', { name: 'Consultorio', exact: true }).getByRole('button', { name, exact: true }).click();
try {
  await page.goto(base + '/consultorio');
  await page.getByText('No se pudo leer la agenda para esta fecha.', { exact: false }).waitFor();
  check('Error de agenda no equivale a cero citas', true);
  await nav('Por revisar');
  await page.locator('.jornada-nombre').filter({ hasText: 'Álvarez' }).click();
  await page.getByRole('tab', { name: 'Resumen', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Marcar preconsulta revisada' }).click();
  await page.getByRole('button', { name: 'Reabrir revisión' }).waitFor();
  check('Abrir respuesta no requiere agenda disponible', true);
  await page.getByRole('tab', { name: 'Estudios', exact: true }).click();
  await page.getByText('No se pudo consultar la carpeta.', { exact: false }).waitFor();
  check('Fallo Storage no se interpreta como no adjunto', !(await page.locator('.resp-record').innerText()).includes('No subió estudios'));
  await page.evaluate(() => { window.__panelQa.errorEstudios = false; });
  await page.getByRole('tabpanel', { name: 'Estudios', exact: true }).getByRole('button', { name: 'Reintentar', exact: true }).click();
  await page.getByText('No encontrado en la carpeta actual').waitFor();
  check('Manifiesto conserva archivo ausente', await page.getByText('Laboratorio de prueba.pdf', { exact: true }).isVisible());
  await page.evaluate(() => { window.__panelQa.archivos = [{ nombre: 'lab.pdf', size: 0 }]; });
  await page.getByRole('button', { name: 'Actualizar archivos' }).click();
  await page.getByText('El almacenamiento informa un archivo de cero bytes.').waitFor();
  check('Advierte cero bytes', true);
  await page.getByRole('button', { name: 'Abrir', exact: true }).click();
  await page.getByRole('button', { name: 'Reintentar apertura' }).waitFor();
  check('Error de firma permite reintentar', true);
  await page.evaluate(() => { window.__panelQa.archivos = [{ nombre: 'lab.pdf', size: 17 }]; });
  await page.getByRole('button', { name: 'Actualizar archivos' }).click();
  await page.getByText('El tamaño informado no coincide con el registro de envío.').waitFor();
  check('Advierte diferencia de bytes', true);
  await page.evaluate(() => { window.__panelQa.errorRespuestas = true; });
  await page.getByRole('button', { name: 'Actualizar datos' }).click();
  await page.getByText('No se pudieron actualizar las respuestas.', { exact: false }).waitFor();
  check('Conserva paciente con aviso de lectura fallida', await page.getByRole('heading', { name: respuestasPrueba[0].paciente.nombre }).isVisible());
  await page.evaluate(() => { window.__panelQa.errorRespuestas = false; window.__panelQa.respuestas[0].consentimiento = { aceptado: true, version: '1' }; });
  await page.getByRole('button', { name: 'Actualizar datos' }).click();
  await page.getByRole('button', { name: 'Marcar preconsulta revisada' }).waitFor();
  check('Version modificada invalida la revision anterior', true);
  await page.getByRole('tab', { name: 'Respuestas', exact: true }).click();
  await page.getByText('Datos del envío y procedencia', { exact: true }).click();
  check('Consentimiento versionado legible', await page.locator('.resp-source .resp-facts > div').filter({ hasText: 'Consentimiento registrado' }).locator('dd').innerText() === 'Sí');
  await page.evaluate(() => { window.__panelQa.respuestas.unshift({ id: 'qa-nueva', creado: '2026-09-10T01:00:00Z', paciente: { nombre: 'Nueva ficticia' }, autoReporte: { hc: {} } }); });
  await page.getByRole('button', { name: 'Actualizar datos' }).click();
  check('Llegada de respuesta no cambia paciente abierta', await page.locator('.consulta-head h1').innerText() === respuestasPrueba[0].paciente.nombre);
  await page.getByRole('button', { name: 'Volver a pendientes' }).click();
  await page.getByRole('searchbox', { name: 'Buscar paciente, teléfono o motivo' }).fill('benitez');
  await page.locator('.jornada-nombre').click();
  await page.getByRole('tab', { name: 'Respuestas', exact: true }).click();
  await page.getByText('Datos del envío y procedencia', { exact: true }).click();
  await page.evaluate(() => { window.__panelQa.demoraRespuestas = 250; });
  await page.getByRole('button', { name: 'Actualizar datos' }).click();
  await page.getByRole('button', { name: 'Eliminar respuesta y archivos' }).click();
  await page.getByText('Se comprobó que la respuesta ya no aparece en la bandeja.').waitFor();
  check('Lectura concurrente no resucita respuesta borrada', await page.locator('.jornada-nombre').count() === 0);
  await page.getByRole('searchbox', { name: 'Buscar paciente, teléfono o motivo' }).fill('alvarez');
  await page.locator('.jornada-nombre').click();
  await page.getByRole('button', { name: 'Marcar preconsulta revisada' }).click();
  await page.getByRole('button', { name: 'Reabrir revisión' }).waitFor();
  await page.evaluate(() => { window.__panelQa.conflictoIndice = true; window.__panelQa.demoraRespuestas = 0; });
  await page.getByRole('button', { name: 'Actualizar datos' }).click();
  await page.getByText('No se pudieron verificar todas las decisiones guardadas.', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Marcar preconsulta revisada' }).waitFor();
  await page.getByRole('button', { name: 'Volver a pendientes' }).click();
  await page.getByText('No verificable', { exact: true }).waitFor();
  check('Conflicto remoto no se oculta como revisada ni desaparece de pendientes', await page.locator('.jornada-nombre').count() === 1);
  check('Sin errores JS', errores.length === 0);
  await fs.writeFile(path.join(output, 'browser-errors-qa.json'), JSON.stringify({ pruebas, errores, alcance: 'Transportes simulados; no valida Supabase ni recuperacion de archivos.' }, null, 2));
  console.log(JSON.stringify({ comprobaciones: pruebas.length, errores }));
} catch (e) {
  await page.screenshot({ path: path.join(output, 'fallo-errores.png'), fullPage: true });
  console.error(JSON.stringify({ pruebas, errores, fallo: e.message }, null, 2)); throw e;
} finally { await browser.close(); }
